BEGIN;
CREATE TABLE skilly.conciliacion_reversa_e3 (
 id_conciliacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_liquidacion BIGINT NOT NULL UNIQUE REFERENCES skilly.liquidacion_cancelacion_e3(id_liquidacion) ON DELETE RESTRICT,
 id_pago BIGINT NOT NULL UNIQUE REFERENCES skilly.pago(id_pago) ON DELETE RESTRICT,
 id_reversa BIGINT NOT NULL UNIQUE REFERENCES skilly.reversa_pago(id_reversa) ON DELETE RESTRICT,
 id_administrador BIGINT NOT NULL REFERENCES skilly.usuario(id_usuario) ON DELETE RESTRICT,
 metodo_pago VARCHAR(30) NOT NULL CHECK (metodo_pago IN ('TRANSFERENCIA','WEBPAY_PLUS')),
 monto_total NUMERIC(12,2) NOT NULL CHECK (monto_total > 0),
 monto_devolucion NUMERIC(12,2) NOT NULL CHECK (monto_devolucion > 0),
 monto_trabajo NUMERIC(12,2) NOT NULL CHECK (monto_trabajo >= 0),
 monto_cargo NUMERIC(12,2) NOT NULL CHECK (monto_cargo >= 0),
 remanente_pendiente NUMERIC(12,2) NOT NULL CHECK (remanente_pendiente >= 0),
 estado VARCHAR(35) NOT NULL CHECK (estado = 'SIMULACION_DOCUMENTAL'),
 fundamento TEXT NOT NULL CHECK (length(trim(fundamento)) >= 30),
 fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT ck_e3_conciliacion_parcial CHECK (monto_devolucion < monto_total),
 CONSTRAINT ck_e3_conciliacion_cuadra CHECK (monto_total = monto_devolucion + monto_trabajo + monto_cargo),
 CONSTRAINT ck_e3_conciliacion_remanente CHECK (remanente_pendiente = monto_trabajo + monto_cargo)
);
GRANT SELECT, INSERT ON skilly.conciliacion_reversa_e3 TO skilly_app;
GRANT USAGE, SELECT ON SEQUENCE skilly.conciliacion_reversa_e3_id_conciliacion_seq TO skilly_app;
COMMIT;
