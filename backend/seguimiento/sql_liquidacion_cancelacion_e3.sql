-- Fase 6C: expediente de liquidación, independiente de pagos históricos.
BEGIN;
CREATE TABLE IF NOT EXISTS skilly.liquidacion_cancelacion_e3 (
 id_liquidacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_expediente BIGINT NOT NULL UNIQUE REFERENCES skilly.expediente_cancelacion_e3(id_expediente) ON DELETE RESTRICT,
 id_pago BIGINT NOT NULL UNIQUE REFERENCES skilly.pago(id_pago) ON DELETE RESTRICT,
 id_reversa BIGINT NULL UNIQUE REFERENCES skilly.reversa_pago(id_reversa) ON DELETE RESTRICT,
 id_administrador BIGINT NOT NULL REFERENCES skilly.usuario(id_usuario) ON DELETE RESTRICT,
 version_politica VARCHAR(64),
 porcentaje_contratado NUMERIC(7,4) NOT NULL CHECK (porcentaje_contratado BETWEEN 0 AND 100),
 monto_total NUMERIC(12,2) NOT NULL CHECK (monto_total > 0),
 monto_trabajo NUMERIC(12,2) NOT NULL CHECK (monto_trabajo >= 0),
 cargo_autorizado NUMERIC(12,2) NOT NULL CHECK (cargo_autorizado >= 0),
 monto_devolucion NUMERIC(12,2) NOT NULL CHECK (monto_devolucion >= 0),
 estado VARCHAR(45) NOT NULL CHECK (estado IN ('REVERSA_SOLICITADA','PENDIENTE_CONCILIACION')),
 fundamento TEXT NOT NULL,
 fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT ck_e3_liq_sum CHECK (monto_trabajo+ cargo_autorizado+ monto_devolucion = monto_total)
);
GRANT SELECT, INSERT ON skilly.liquidacion_cancelacion_e3 TO skilly_app;
GRANT USAGE, SELECT ON SEQUENCE skilly.liquidacion_cancelacion_e3_id_liquidacion_seq TO skilly_app;
COMMIT;
