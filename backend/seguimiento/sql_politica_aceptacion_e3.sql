-- Solo tabla de aceptación previa al pago. Nunca altera registros históricos.
BEGIN;
CREATE TABLE IF NOT EXISTS skilly.aceptacion_politica_cancelacion_e3 (
 id_aceptacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_prestacion BIGINT NOT NULL UNIQUE REFERENCES skilly.prestacion_servicio(id_prestacion) ON DELETE RESTRICT,
 porcentaje_aceptado NUMERIC(7,4) NOT NULL CHECK (porcentaje_aceptado >= 0 AND porcentaje_aceptado <= 100),
 version_politica VARCHAR(64) NOT NULL,
 texto_aceptado TEXT NOT NULL,
 fecha_aceptacion TIMESTAMPTZ NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT ON skilly.aceptacion_politica_cancelacion_e3 TO skilly_app;
GRANT USAGE, SELECT ON SEQUENCE skilly.aceptacion_politica_cancelacion_e3_id_aceptacion_seq TO skilly_app;
COMMIT;
