-- Prepara las tablas E3 administradas por SQL para una instalación nueva.
-- Requiere que las tablas, PK y FK de 01–03 ya estén creadas. Solo define esquema.
BEGIN;
SET LOCAL search_path TO skilly;

-- Mantiene una sola cuenta principal activa y registra cada cambio administrativo.
CREATE TABLE cuenta_bancaria_skilly (
    id_cuenta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titular varchar(180) NOT NULL CHECK (length(btrim(titular)) > 0),
    rut_titular varchar(12) NOT NULL CHECK (length(btrim(rut_titular)) > 0),
    banco varchar(120) NOT NULL CHECK (length(btrim(banco)) > 0),
    tipo_cuenta varchar(24) NOT NULL CHECK (tipo_cuenta IN ('CORRIENTE', 'VISTA', 'CUENTA_RUT', 'AHORRO')),
    numero_cuenta varchar(32) NOT NULL CHECK (numero_cuenta ~ '^[0-9]{5,32}$'),
    correo varchar(254) NOT NULL CHECK (length(btrim(correo)) > 0),
    activa boolean NOT NULL DEFAULT false,
    principal boolean NOT NULL DEFAULT false,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    id_usuario_creacion bigint REFERENCES usuario(id_usuario),
    id_usuario_modificacion bigint REFERENCES usuario(id_usuario),
    CONSTRAINT principal_requiere_activa CHECK (NOT principal OR activa),
    CONSTRAINT cuenta_bancaria_identidad_uniq UNIQUE (banco, tipo_cuenta, numero_cuenta, rut_titular)
);

CREATE UNIQUE INDEX uq_cuenta_bancaria_principal
    ON cuenta_bancaria_skilly (principal) WHERE principal IS TRUE;

CREATE TABLE cuenta_bancaria_skilly_historial (
    id_cambio bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta bigint NOT NULL REFERENCES cuenta_bancaria_skilly(id_cuenta) ON DELETE RESTRICT,
    accion varchar(25) NOT NULL CHECK (accion IN ('CREAR', 'MODIFICAR', 'ACTIVAR', 'DESACTIVAR', 'PRINCIPAL')),
    datos_anteriores jsonb,
    datos_nuevos jsonb NOT NULL,
    id_usuario_skilly bigint REFERENCES usuario(id_usuario),
    fecha_cambio timestamptz NOT NULL DEFAULT now()
);

-- Cada pago conserva los datos bancarios emitidos aunque se modifique la cuenta principal.
CREATE TABLE instruccion_transferencia_skilly (
    id_instruccion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago bigint NOT NULL UNIQUE REFERENCES pago(id_pago) ON DELETE RESTRICT,
    id_cuenta bigint NOT NULL REFERENCES cuenta_bancaria_skilly(id_cuenta) ON DELETE RESTRICT,
    titular_fijado varchar(180) NOT NULL,
    rut_titular_fijado varchar(12) NOT NULL,
    banco_fijado varchar(120) NOT NULL,
    tipo_cuenta_fijado varchar(24) NOT NULL,
    numero_cuenta_fijado varchar(32) NOT NULL,
    correo_fijado varchar(254) NOT NULL,
    fecha_emision timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT instruccion_datos_completos CHECK (
        length(btrim(titular_fijado)) > 0
        AND length(btrim(rut_titular_fijado)) > 0
        AND length(btrim(banco_fijado)) > 0
        AND length(btrim(tipo_cuenta_fijado)) > 0
        AND numero_cuenta_fijado ~ '^[0-9]{5,32}$'
        AND length(btrim(correo_fijado)) > 0
    )
);

-- Impide cambiar la instrucción emitida aun si se altera la cuenta de origen.
CREATE FUNCTION impedir_cambio_instruccion_transferencia() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Las instrucciones bancarias emitidas no pueden modificarse ni eliminarse';
END;
$$;

CREATE TRIGGER tg_instruccion_transferencia_inmutable
    BEFORE UPDATE OR DELETE ON instruccion_transferencia_skilly
    FOR EACH ROW EXECUTE FUNCTION impedir_cambio_instruccion_transferencia();

-- Preserva la versión y el texto exactos que se aceptaron por prestación.
CREATE TABLE aceptacion_politica_cancelacion_e3 (
    id_aceptacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestacion bigint NOT NULL UNIQUE REFERENCES prestacion_servicio(id_prestacion) ON DELETE RESTRICT,
    porcentaje_aceptado numeric(7,4) NOT NULL CHECK (porcentaje_aceptado BETWEEN 0 AND 100),
    version_politica varchar(64) NOT NULL,
    texto_aceptado text NOT NULL,
    fecha_aceptacion timestamptz NOT NULL DEFAULT now()
);

-- Guarda metadatos y referencia privada de cada adjunto sin almacenar su contenido.
CREATE TABLE archivo_entrega_e3 (
    id_archivo bigserial PRIMARY KEY,
    id_entrega bigint NOT NULL REFERENCES entrega(id_entrega) ON DELETE RESTRICT,
    nombre_original varchar(255) NOT NULL,
    ruta_privada varchar(255) NOT NULL UNIQUE,
    tipo_mime varchar(120) NOT NULL,
    tamanio_bytes bigint NOT NULL CHECK (tamanio_bytes > 0 AND tamanio_bytes <= 10485760),
    fecha_subida timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX archivo_entrega_e3_entrega_idx ON archivo_entrega_e3 (id_entrega);

-- Acota cada prestación a un expediente pendiente y conserva el historial resuelto.
CREATE TABLE expediente_cancelacion_e3 (
    id_expediente bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestacion bigint NOT NULL REFERENCES prestacion_servicio(id_prestacion) ON DELETE RESTRICT,
    id_reclamo bigint REFERENCES reclamo_prestacion(id_reclamo) ON DELETE RESTRICT,
    id_avance bigint REFERENCES avance_servicio(id_avance) ON DELETE RESTRICT,
    origen varchar(20) NOT NULL CHECK (origen IN ('ORGANIZACION', 'PROFESIONAL')),
    motivo varchar(120) NOT NULL,
    descripcion text NOT NULL,
    evidencia_nombre varchar(150),
    evidencia_mime varchar(40),
    evidencia_sha256 varchar(64),
    evidencia_contenido bytea,
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    estado varchar(25) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'RESUELTO')),
    decision varchar(45),
    fundamento text,
    fecha_resolucion timestamptz,
    id_administrador bigint REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    porcentaje_referencia numeric(7,4),
    monto_total numeric(12,2),
    monto_trabajo numeric(12,2),
    cargo_ejecutado numeric(12,2),
    cargo_teorico numeric(12,2),
    devolucion_propuesta numeric(12,2)
);

CREATE INDEX ix_e3_expediente_fecha ON expediente_cancelacion_e3 (fecha_registro DESC);
CREATE UNIQUE INDEX ux_e3_expediente_pendiente
    ON expediente_cancelacion_e3 (id_prestacion) WHERE estado = 'PENDIENTE';

-- Comprueba que el desglose autorizado cuadre con el pago original.
CREATE TABLE liquidacion_cancelacion_e3 (
    id_liquidacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_expediente bigint NOT NULL UNIQUE REFERENCES expediente_cancelacion_e3(id_expediente) ON DELETE RESTRICT,
    id_pago bigint NOT NULL UNIQUE REFERENCES pago(id_pago) ON DELETE RESTRICT,
    id_reversa bigint UNIQUE REFERENCES reversa_pago(id_reversa) ON DELETE RESTRICT,
    id_administrador bigint NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    version_politica varchar(64),
    porcentaje_contratado numeric(7,4) NOT NULL CHECK (porcentaje_contratado BETWEEN 0 AND 100),
    monto_total numeric(12,2) NOT NULL CHECK (monto_total > 0),
    monto_trabajo numeric(12,2) NOT NULL CHECK (monto_trabajo >= 0),
    cargo_autorizado numeric(12,2) NOT NULL CHECK (cargo_autorizado >= 0),
    monto_devolucion numeric(12,2) NOT NULL CHECK (monto_devolucion >= 0),
    estado varchar(45) NOT NULL CHECK (estado IN ('REVERSA_SOLICITADA', 'PENDIENTE_CONCILIACION', 'DISTRIBUCION_SIMULADA')),
    fundamento text NOT NULL,
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_e3_liq_sum CHECK (monto_trabajo + cargo_autorizado + monto_devolucion = monto_total)
);

-- Registra la simulación documental de una reversa parcial y su remanente.
CREATE TABLE conciliacion_reversa_e3 (
    id_conciliacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_liquidacion bigint NOT NULL UNIQUE REFERENCES liquidacion_cancelacion_e3(id_liquidacion) ON DELETE RESTRICT,
    id_pago bigint NOT NULL UNIQUE REFERENCES pago(id_pago) ON DELETE RESTRICT,
    id_reversa bigint NOT NULL UNIQUE REFERENCES reversa_pago(id_reversa) ON DELETE RESTRICT,
    id_administrador bigint NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    metodo_pago varchar(30) NOT NULL CHECK (metodo_pago IN ('TRANSFERENCIA', 'WEBPAY_PLUS')),
    monto_total numeric(12,2) NOT NULL CHECK (monto_total > 0),
    monto_devolucion numeric(12,2) NOT NULL CHECK (monto_devolucion > 0),
    monto_trabajo numeric(12,2) NOT NULL CHECK (monto_trabajo >= 0),
    monto_cargo numeric(12,2) NOT NULL CHECK (monto_cargo >= 0),
    remanente_pendiente numeric(12,2) NOT NULL CHECK (remanente_pendiente >= 0),
    estado varchar(35) NOT NULL CHECK (estado IN ('SIMULACION_DOCUMENTAL', 'DISTRIBUCION_SIMULADA')),
    fundamento text NOT NULL CHECK (length(trim(fundamento)) >= 30),
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_e3_conciliacion_cuadra CHECK (monto_total = monto_devolucion + monto_trabajo + monto_cargo),
    CONSTRAINT ck_e3_conciliacion_parcial CHECK (monto_devolucion < monto_total),
    CONSTRAINT ck_e3_conciliacion_remanente CHECK ((estado = 'SIMULACION_DOCUMENTAL' AND remanente_pendiente = monto_trabajo + monto_cargo) OR (estado = 'DISTRIBUCION_SIMULADA' AND remanente_pendiente = 0))
);

COMMIT;
