barrier = threading.Barrier(2, timeout=12)

def intento(correo):
    from django.db import connections as conn
    try:
        usuario = Usuario.objects.get(correo=correo)
        barrier.wait()
        factory = APIRequestFactory()
        req = factory.post(f'/api/coordinacion/administracion/solicitudes/{solicitud_id}/asignacion/',
                           {'modo':'AUTOASIGNAR'}, format='json')
        force_authenticate(req, user=usuario)
        resp = AsignacionSolicitudSeguraAdministracionView.as_view()(req, id_solicitud=solicitud_id)
        return (correo, resp.status_code, str(getattr(resp,'data',{}))[:280])
    finally:
        conn.close_all()

