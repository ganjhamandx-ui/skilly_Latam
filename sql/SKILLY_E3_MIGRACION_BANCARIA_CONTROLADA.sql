BEGIN;
DO $$ BEGIN
 IF current_database() <> 'skilly' OR to_regclass('skilly.pago') IS NULL OR to_regclass('skilly.usuario') IS NULL OR to_regclass('skilly.cuenta_bancaria_skilly') IS NOT NULL OR to_regclass('skilly.cuenta_bancaria_skilly_historial') IS NOT NULL OR to_regclass('skilly.instruccion_transferencia_skilly') IS NOT NULL THEN
   RAISE EXCEPTION 'Migracion bancaria bloqueada: verificar BD skilly y tablas pago/usuario';
 END IF;
END $$;
CREATE TABLE skilly.cuenta_bancaria_skilly (
 id_cuenta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titular VARCHAR(180) NOT NULL CHECK (length(btrim(titular))>0),
 rut_titular VARCHAR(12) NOT NULL CHECK (length(btrim(rut_titular))>0),
 banco VARCHAR(120) NOT NULL CHECK (length(btrim(banco))>0),
 tipo_cuenta VARCHAR(24) NOT NULL CHECK (tipo_cuenta IN ('CORRIENTE','VISTA','CUENTA_RUT','AHORRO')),
 numero_cuenta VARCHAR(32) NOT NULL CHECK (numero_cuenta ~ '^[0-9]{5,32}$'),
 correo VARCHAR(254) NOT NULL CHECK (length(btrim(correo))>0),
 activa BOOLEAN NOT NULL DEFAULT FALSE,
 principal BOOLEAN NOT NULL DEFAULT FALSE,
 fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
 fecha_modificacion TIMESTAMPTZ NOT NULL DEFAULT now(),
 id_usuario_creacion BIGINT REFERENCES skilly.usuario(id_usuario),
 id_usuario_modificacion BIGINT REFERENCES skilly.usuario(id_usuario),
 CONSTRAINT principal_requiere_activa CHECK (NOT principal OR activa),
 CONSTRAINT cuenta_bancaria_identidad_uniq UNIQUE(banco,tipo_cuenta,numero_cuenta,rut_titular)
);
CREATE UNIQUE INDEX uq_cuenta_bancaria_principal ON skilly.cuenta_bancaria_skilly(principal) WHERE principal IS TRUE;
CREATE TABLE skilly.cuenta_bancaria_skilly_historial (
 id_cambio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cuenta BIGINT NOT NULL REFERENCES skilly.cuenta_bancaria_skilly(id_cuenta) ON DELETE RESTRICT,
 accion VARCHAR(25) NOT NULL CHECK (accion IN ('CREAR','MODIFICAR','ACTIVAR','DESACTIVAR','PRINCIPAL')),
 datos_anteriores JSONB,
 datos_nuevos JSONB NOT NULL,
 id_usuario_skilly BIGINT REFERENCES skilly.usuario(id_usuario),
 fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE skilly.instruccion_transferencia_skilly (
 id_instruccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pago BIGINT NOT NULL UNIQUE REFERENCES skilly.pago(id_pago) ON DELETE RESTRICT,
 id_cuenta BIGINT NOT NULL REFERENCES skilly.cuenta_bancaria_skilly(id_cuenta) ON DELETE RESTRICT,
 titular_fijado VARCHAR(180) NOT NULL,
 rut_titular_fijado VARCHAR(12) NOT NULL,
 banco_fijado VARCHAR(120) NOT NULL,
 tipo_cuenta_fijado VARCHAR(24) NOT NULL,
 numero_cuenta_fijado VARCHAR(32) NOT NULL,
 correo_fijado VARCHAR(254) NOT NULL,
 fecha_emision TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT instruccion_datos_completos CHECK (
  length(btrim(titular_fijado))>0 AND length(btrim(rut_titular_fijado))>0 AND
  length(btrim(banco_fijado))>0 AND length(btrim(tipo_cuenta_fijado))>0 AND
  numero_cuenta_fijado ~ '^[0-9]{5,32}$' AND length(btrim(correo_fijado))>0)
);
CREATE FUNCTION skilly.impedir_cambio_instruccion_transferencia() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Las instrucciones bancarias emitidas no pueden modificarse ni eliminarse'; END $$;
CREATE TRIGGER tg_instruccion_transferencia_inmutable BEFORE UPDATE OR DELETE ON skilly.instruccion_transferencia_skilly
 FOR EACH ROW EXECUTE FUNCTION skilly.impedir_cambio_instruccion_transferencia();
-- Permisos delimitados a las nuevas tablas y secuencias, sin tocar esquemas económicos actuales.
GRANT SELECT,INSERT,UPDATE ON skilly.cuenta_bancaria_skilly TO skilly_app;
GRANT SELECT,INSERT ON skilly.cuenta_bancaria_skilly_historial TO skilly_app;
GRANT SELECT,INSERT ON skilly.instruccion_transferencia_skilly TO skilly_app;
GRANT USAGE,SELECT ON SEQUENCE skilly.cuenta_bancaria_skilly_id_cuenta_seq,
 skilly.cuenta_bancaria_skilly_historial_id_cambio_seq,
 skilly.instruccion_transferencia_skilly_id_instruccion_seq TO skilly_app;
COMMIT;
