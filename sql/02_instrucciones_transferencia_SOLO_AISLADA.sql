-- SKILLY E3: INSTRUCCIONES BANCARIAS POR PAGO, SOLO ENTORNO AISLADO
-- Ejecutar en pgAdmin conectado EXCLUSIVAMENTE a skilly_test_concurrencia.
-- No ejecutar en base principal. No contiene datos reales.
BEGIN;
DO $$ BEGIN
  IF current_database() <> 'skilly_test_concurrencia' THEN
    RAISE EXCEPTION 'BLOQUEADO: esta migracion solo admite skilly_test_concurrencia';
  END IF;
  IF to_regclass('public.cuenta_bancaria_skilly') IS NULL THEN
    RAISE EXCEPTION 'Falta tabla de cuentas bancarias en la base aislada';
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS public.instruccion_transferencia_skilly (
    id_instruccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL UNIQUE,
    id_cuenta BIGINT NOT NULL REFERENCES public.cuenta_bancaria_skilly(id_cuenta) ON DELETE RESTRICT,
    titular_fijado VARCHAR(180) NOT NULL,
    rut_titular_fijado VARCHAR(12) NOT NULL,
    banco_fijado VARCHAR(120) NOT NULL,
    tipo_cuenta_fijado VARCHAR(24) NOT NULL,
    numero_cuenta_fijado VARCHAR(32) NOT NULL,
    correo_fijado VARCHAR(254) NOT NULL,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT instruccion_datos_completos CHECK (
      length(btrim(titular_fijado)) > 0 AND length(btrim(rut_titular_fijado)) > 0
      AND length(btrim(banco_fijado)) > 0 AND length(btrim(tipo_cuenta_fijado)) > 0
      AND numero_cuenta_fijado ~ '^[0-9]{5,32}$' AND length(btrim(correo_fijado)) > 0
    )
);
-- Una instruccion emitida es inmutable. Cambiar cuenta principal NO modifica pagos anteriores.
CREATE OR REPLACE FUNCTION public.impedir_cambio_instruccion_transferencia()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'La instruccion bancaria emitida es inmutable (%).', TG_OP;
END $$;
CREATE TRIGGER trg_instruccion_inmutable
BEFORE UPDATE OR DELETE ON public.instruccion_transferencia_skilly
FOR EACH ROW EXECUTE FUNCTION public.impedir_cambio_instruccion_transferencia();
-- Grants especificos para Django en la BD aislada, no sobre todas las secuencias.
GRANT SELECT, INSERT ON public.instruccion_transferencia_skilly TO skilly_app;
GRANT USAGE, SELECT ON SEQUENCE public.instruccion_transferencia_skilly_id_instruccion_seq TO skilly_app;
COMMIT;
