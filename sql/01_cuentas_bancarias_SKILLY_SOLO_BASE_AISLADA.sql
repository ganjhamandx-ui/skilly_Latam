CREATE TABLE IF NOT EXISTS public.cuenta_bancaria_skilly (
 id_cuenta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titular VARCHAR(180) NOT NULL CHECK (length(btrim(titular)) > 0),
 rut_titular VARCHAR(12) NOT NULL CHECK (length(btrim(rut_titular)) > 0),
 banco VARCHAR(120) NOT NULL CHECK (length(btrim(banco)) > 0),
 tipo_cuenta VARCHAR(24) NOT NULL CHECK (tipo_cuenta IN ('CORRIENTE','VISTA','CUENTA_RUT','AHORRO')),
 numero_cuenta VARCHAR(32) NOT NULL CHECK (numero_cuenta ~ '^[0-9]{5,32}$'),
 correo VARCHAR(254) NOT NULL CHECK (length(btrim(correo)) > 0),
 activa BOOLEAN NOT NULL DEFAULT FALSE,
 principal BOOLEAN NOT NULL DEFAULT FALSE,
 fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
 fecha_modificacion TIMESTAMPTZ NOT NULL DEFAULT now(),
 id_usuario_creacion BIGINT,
 id_usuario_modificacion BIGINT,
 CONSTRAINT principal_requiere_activa CHECK (NOT principal OR activa),
 CONSTRAINT cuenta_bancaria_identidad_uniq UNIQUE (banco,tipo_cuenta,numero_cuenta,rut_titular)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_cuenta_bancaria_principal
 ON public.cuenta_bancaria_skilly(principal) WHERE principal IS TRUE;
CREATE TABLE IF NOT EXISTS public.cuenta_bancaria_skilly_historial (
 id_cambio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cuenta BIGINT NOT NULL REFERENCES public.cuenta_bancaria_skilly(id_cuenta) ON DELETE RESTRICT,
 accion VARCHAR(25) NOT NULL CHECK (accion IN ('CREAR','MODIFICAR','ACTIVAR','DESACTIVAR','PRINCIPAL')),
 datos_anteriores JSONB,
 datos_nuevos JSONB NOT NULL,
 id_usuario_skilly BIGINT,
 fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT now()
);
